// Command language-stdlib derives the shared library snapshot from preserved upstream source.
package main

import (
	"bytes"
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"
	"unicode/utf8"
)

func main() {
	source := flag.String("source", "stdfunc.cherri", "preserved upstream source file")
	output := flag.String("output", "internal/language/modules/stdfunc_source_generated.go", "generated Go source file")
	check := flag.Bool("check", false, "reject a missing or stale snapshot without writing")
	flag.Parse()
	if err := generate(*source, *output, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(source, output string, check bool) error {
	raw, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	if len(raw) == 0 || !utf8.Valid(raw) {
		return fmt.Errorf("preserved standard library must be nonempty UTF-8")
	}
	text := fmt.Sprintf("// Code generated by go run ./tools/language-stdlib; DO NOT EDIT.\n// Source: stdfunc.cherri; SHA256: %x.\n\npackage modules\n\nconst standardLibrarySource = %s\n", sha256.Sum256(raw), strconv.Quote(string(raw)))
	generated, err := format.Source([]byte(text))
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(output)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, generated) {
			return fmt.Errorf("shared standard library snapshot is stale; run go generate .")
		}
		return nil
	}
	if err := os.MkdirAll(filepath.Dir(output), 0755); err != nil {
		return err
	}
	return os.WriteFile(output, generated, 0644)
}
