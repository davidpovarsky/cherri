// Publication and provider receipts below are synthetic intake controls. The
// separate opt-in original test reads independently pinned real receipts.
func docsProcessPublicationFixture(t *testing.T) *finalProvenanceFixture {
	t.Helper()
	f := &finalProvenanceFixture{
		originals: t.TempDir(),
		expected:  finalProvenanceExpected{Sources: map[string]finalProvenanceSource{}, Publications: map[string]finalProvenancePublication{}, Files: map[string]finalProvenanceFile{}},
		manifest:  finalProvenanceManifest{Files: map[string]string{}, SourceDirectories: map[string]string{"docs": t.TempDir()}},
	}
	s := finalProvenanceSource{"davidpovarsky/cherrilang.org", strings.Repeat("a", 40), strings.Repeat("b", 40), "refs/heads/agent/docs-fixture", "refs/heads/main"}
	f.expected.Sources["docs"] = s
	f.expected.Sources["compiler"] = finalProvenanceSource{SHA: strings.Repeat("c", 40)}
	root, previous := f.manifest.SourceDirectories["docs"], strings.Repeat("d", 40)
	p := finalProvenancePublication{Format: docsProcessPublicationFormat, Result: "docs-preflight", Push: "docs-push", Ref: "docs-ref", Commit: "docs-commit",
		PushStreams: &finalProvenanceStreams{"docs-push.stdout", "docs-push.stderr"}, Receipts: map[string]string{}, Streams: map[string]finalProvenanceStreams{}}
	sourceOriginals := map[string]any{}
	for _, name := range []string{"docsIntake", "docsRun", "s4Intake", "s4Handoff"} {
		id := "preflight-" + name
		f.put(t, id, map[string]any{"synthetic": name})
		p.Receipts["preflight."+name] = id
		sourceOriginals[name] = map[string]any{"path": f.manifest.Files[id], "sha256": f.expected.Files[id].SHA256}
	}
	start := time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)
	f.put(t, p.Result, map[string]any{"schema": "cherri.docs-publication-preflight/v1", "atUtc": start.Format(time.RFC3339),
		"previousMain": previous, "docsCommit": s.SHA, "compilerCommit": f.expected.Sources["compiler"].SHA,
		"normalFastForwardOnly": true, "cleanDocsSource": true, "compilerMainOr179AcceptanceGranted": false, "sourceOriginals": sourceOriginals})
	stderr := "To https://github.com/davidpovarsky/cherrilang.org.git\n   ddddddd..aaaaaaa  " + s.SHA + " -> main\n"
	f.putBytes(t, p.PushStreams.Stdout, []byte{})
	f.putBytes(t, p.PushStreams.Stderr, []byte(stderr))
	f.put(t, p.Push, map[string]any{"command": []string{"sudo", "-u", "ubuntu", "git", "-C", root, "-c", "remote.origin.mirror=false", "-c", "credential.helper=", "-c", "credential.helper=!gh auth git-credential", "push", "origin", s.SHA + ":refs/heads/main"},
		"startedUtc": start.Add(time.Second).Format(time.RFC3339), "finishedUtc": start.Add(2 * time.Second).Format(time.RFC3339), "exitCode": 0,
		"stdoutSha256": f.expected.Files[p.PushStreams.Stdout].SHA256, "stderrSha256": f.expected.Files[p.PushStreams.Stderr].SHA256})
	summary, _ := json.Marshal(map[string]any{"preflightPath": f.manifest.Files[p.Result], "preflightSha256": f.expected.Files[p.Result].SHA256, "exitCode": 0, "stderr": stderr, "afterRemoteMain": s.SHA + "\trefs/heads/main"})
	structured := map[string]any{"ok": true, "returncode": 0, "output": string(summary)}
	text, _ := json.Marshal(structured)
	p.Receipts["provider_response"] = "provider"
	f.put(t, "provider", map[string]any{"isError": false, "structuredContent": structured, "content": []any{map[string]any{"type": "text", "text": string(text)}}})
	f.put(t, p.Ref, map[string]any{"ref": s.PublishedRef, "url": "https://api.github.com/repos/" + s.Repository + "/git/refs/heads/main", "object": map[string]any{"sha": s.SHA, "type": "commit"}})
	f.put(t, p.Commit, map[string]any{"sha": s.SHA, "tree": map[string]any{"sha": s.Tree}})
	// Independent command and stream inventory, not generated by the validator.
	prefix := []string{"/usr/bin/git", "--no-replace-objects", "-C", root, "-c", "core.fsmonitor=false", "-c", "core.untrackedCache=false", "-c", "core.ignoreStat=false"}
	queries := [][]string{
		{"rev-parse", "HEAD"}, {"rev-parse", "HEAD^{tree}"}, {"symbolic-ref", "-q", "HEAD"},
		{"status", "--porcelain=v1", "--untracked-files=all", "--ignore-submodules=none"}, {"diff", "--name-only", "HEAD", "--"},
		{"remote", "get-url", "--all", "origin"}, {"remote", "get-url", "--push", "--all", "origin"},
		{"merge-base", "--is-ancestor", previous, s.SHA}, {"ls-files", "-v", "-z"}, {"for-each-ref", "--format=%(refname)", "refs/replace/"},
	}
	names := []string{"post-head", "post-tree", "post-ref", "post-status", "post-diff", "post-origin", "post-push-origin", "post-base", "post-index", "post-replace"}
	outputs := []string{s.SHA + "\n", s.Tree + "\n", s.LocalRef + "\n", "", "", "https://github.com/" + s.Repository + ".git\n", "https://github.com/" + s.Repository + ".git\n", "", "H index.md\x00", ""}
	var rows []any
	for i, name := range names {
		pair := finalProvenanceStreams{name + ".stdout", name + ".stderr"}
		p.Streams[name] = pair
		f.putBytes(t, pair.Stdout, []byte(outputs[i]))
		f.putBytes(t, pair.Stderr, []byte{})
		rows = append(rows, map[string]any{"label": name, "argv": append(append([]string{}, prefix...), queries[i]...), "exitCode": 0, "timedOut": false,
			"startedUtc": start.Add(time.Duration(3+2*i) * time.Second).Format(time.RFC3339), "finishedUtc": start.Add(time.Duration(4+2*i) * time.Second).Format(time.RFC3339),
			"stdoutSha256": f.expected.Files[pair.Stdout].SHA256, "stderrSha256": f.expected.Files[pair.Stderr].SHA256})
	}
	p.Receipts["source_after"] = "source-after"
	f.put(t, "source-after", map[string]any{"schema": "cherri-docs-publication-source-observation/1", "sourceDirectory": root,
		"sourceCommit": s.SHA, "sourceTree": s.Tree, "localRef": s.LocalRef, "previousMain": previous,
		"startedUtc": start.Add(3 * time.Second).Format(time.RFC3339), "finishedUtc": start.Add(23 * time.Second).Format(time.RFC3339), "commands": rows})
	f.expected.Publications["docs"] = p
	return f
}

func docsProcessPublicationInputs(f *finalProvenanceFixture) (*finalProvenanceInputs, error) {
	in := &finalProvenanceInputs{Expected: f.expected, Manifest: f.manifest, JSON: map[string]map[string]any{}, Bytes: map[string][]byte{}}
	for id, pin := range f.expected.Files {
		b, err := finalProvenanceRead(f.manifest.Files[id], pin, true)
		if err != nil {
			return nil, err
		}
		in.Bytes[id] = b
	}
	return in, nil
}

func TestDocsProcessPublicationControls(t *testing.T) {
	mutateObject := func(f *finalProvenanceFixture, id string, change func(map[string]any)) {
		o := f.object(t, id)
		change(o)
		f.put(t, id, o)
	}
	tests := []struct {
		name   string
		mutate func(*finalProvenanceFixture)
	}{
		{"positive-original-format", nil},
		{"wrong-docs-source", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-preflight", func(o map[string]any) { o["docsCommit"] = strings.Repeat("e", 40) })
		}},
		{"wrong-compiler-source", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-preflight", func(o map[string]any) { o["compilerCommit"] = strings.Repeat("e", 40) })
		}},
		{"force-argument", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-push", func(o map[string]any) { o["command"] = append(o["command"].([]any), "--force") })
		}},
		{"second-ref", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-push", func(o map[string]any) { o["command"] = append(o["command"].([]any), "HEAD:refs/heads/other") })
		}},
		{"wrong-repository-directory", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-push", func(o map[string]any) { o["command"].([]any)[5] = "/tmp/unrelated" })
		}},
		{"failed-push", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-push", func(o map[string]any) { o["exitCode"] = 1 })
		}},
		{"reversed-push-time", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-push", func(o map[string]any) { o["finishedUtc"] = "2019-01-01T00:00:00Z" })
		}},
		{"missing-provider-original", func(f *finalProvenanceFixture) { os.Remove(f.manifest.Files["provider"]) }},
		{"provider-contradiction", func(f *finalProvenanceFixture) {
			mutateObject(f, "provider", func(o map[string]any) { o["isError"] = true })
		}},
		{"provider-content-tamper", func(f *finalProvenanceFixture) {
			mutateObject(f, "provider", func(o map[string]any) { o["content"].([]any)[0].(map[string]any)["text"] = "{}" })
		}},
		{"preflight-original-missing", func(f *finalProvenanceFixture) { delete(f.expected.Files, "preflight-s4Handoff") }},
		{"remote-source-mismatch", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-ref", func(o map[string]any) { o["object"].(map[string]any)["sha"] = strings.Repeat("f", 40) })
		}},
		{"remote-tree-mismatch", func(f *finalProvenanceFixture) {
			mutateObject(f, "docs-commit", func(o map[string]any) { o["tree"].(map[string]any)["sha"] = strings.Repeat("f", 40) })
		}},
		{"post-witness-before-push", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) { o["startedUtc"] = "2019-01-01T00:00:00Z" })
		}},
		{"post-wrong-source", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) { o["sourceCommit"] = strings.Repeat("f", 40) })
		}},
		{"post-command-missing", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) { o["commands"] = o["commands"].([]any)[:9] })
		}},
		{"post-command-timed-out", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) { o["commands"].([]any)[0].(map[string]any)["timedOut"] = true })
		}},
		{"post-ancestry-failed", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) { o["commands"].([]any)[7].(map[string]any)["exitCode"] = 1 })
		}},
		{"post-ancestry-reversed", func(f *finalProvenanceFixture) {
			mutateObject(f, "source-after", func(o map[string]any) {
				a := o["commands"].([]any)[7].(map[string]any)["argv"].([]any)
				a[len(a)-1], a[len(a)-2] = a[len(a)-2], a[len(a)-1]
			})
		}},
		{"dirty-post-status", func(f *finalProvenanceFixture) {
			f.putBytes(t, "post-status.stdout", []byte(" M index.md\n"))
			mutateObject(f, "source-after", func(o map[string]any) {
				o["commands"].([]any)[3].(map[string]any)["stdoutSha256"] = f.expected.Files["post-status.stdout"].SHA256
			})
		}},
		{"hidden-index", func(f *finalProvenanceFixture) {
			f.putBytes(t, "post-index.stdout", []byte("h index.md\x00"))
			mutateObject(f, "source-after", func(o map[string]any) {
				o["commands"].([]any)[8].(map[string]any)["stdoutSha256"] = f.expected.Files["post-index.stdout"].SHA256
			})
		}},
		{"unrepinned-stream-tamper", func(f *finalProvenanceFixture) {
			os.WriteFile(f.manifest.Files["docs-push.stderr"], []byte("tampered"), 0600)
		}},
		{"duplicate-stream", func(f *finalProvenanceFixture) {
			p := f.expected.Publications["docs"]
			p.Streams["post-head"] = p.Streams["post-tree"]
			f.expected.Publications["docs"] = p
		}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			f := docsProcessPublicationFixture(t)
			if test.mutate != nil {
				test.mutate(f)
			}
			in, err := docsProcessPublicationInputs(f)
			if err == nil {
				err = finalProvenanceValidatePublication(in, "docs")
			}
			if (err == nil) != (test.mutate == nil) {
				t.Fatalf("unexpected control result: %v", err)
			}
		})
	}
}

func TestDocsProcessPublicationActualOriginals(t *testing.T) {
	path, digest := os.Getenv("CHERRI_DOCS_PROCESS_PUBLICATION_ORIGINAL_EXPECTED"), os.Getenv("CHERRI_DOCS_PROCESS_PUBLICATION_ORIGINAL_EXPECTED_SHA256")
	if path == "" && digest == "" {
		t.Skip("independently selected actual originals are not configured")
	}
	var spec struct {
		Schema      string                         `json:"schema"`
		Docs        finalProvenanceSource          `json:"docs"`
		Compiler    finalProvenanceSource          `json:"compiler"`
		Root        string                         `json:"root"`
		Publication finalProvenancePublication     `json:"publication"`
		Files       map[string]finalProvenanceFile `json:"files"`
		Paths       map[string]string              `json:"paths"`
	}
	if err := finalProvenanceReadContext(path, digest, &spec); err != nil {
		t.Fatal(err)
	}
	if spec.Schema != "cherri-docs-process-publication-original-intake/1" || spec.Publication.Format != docsProcessPublicationFormat || len(spec.Files) != len(spec.Paths) || !filepath.IsAbs(spec.Root) {
		t.Fatal("invalid actual docs-original context")
	}
	f := &finalProvenanceFixture{expected: finalProvenanceExpected{Sources: map[string]finalProvenanceSource{"docs": spec.Docs, "compiler": spec.Compiler}, Publications: map[string]finalProvenancePublication{"docs": spec.Publication}, Files: spec.Files}, manifest: finalProvenanceManifest{Files: spec.Paths, SourceDirectories: map[string]string{"docs": spec.Root}}}
	in, err := docsProcessPublicationInputs(f)
	if err != nil {
		t.Fatal(err)
	}
	if err = finalProvenanceValidatePublication(in, "docs"); err != nil {
		t.Fatal(err)
	}
	t.Logf("Actual docs publication/source originals accepted: source=%s tree=%s files=%d; no global acceptance", spec.Docs.SHA, spec.Docs.Tree, len(spec.Files))
}
